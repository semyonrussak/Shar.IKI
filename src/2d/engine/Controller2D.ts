import * as THREE from 'three';
import { RenderEngine2D } from './RenderEngine2D';

export class Controller2D {
    private engine: RenderEngine2D; // Ссылка на экземпляр движка, переданный в конструкторе. Через неё будем получать canvas (для навешивания слушателей) и камеру (для управления).
    private isPanning = false;      // Флаг, показывающий, зажата ли левая кнопка мыши в данный момент. Когда true, движение мыши вызовет панорамирование; когда false — игнорируется.
    private lastMouseX = 0;        
    private lastMouseY = 0;         // Хранят предыдущие координаты мыши (в пикселях экрана). Используются для вычисления дельты перемещения (на сколько сдвинулась мышь с прошлого кадра).
    private readonly minZoom = 0.1;
    private readonly maxZoom = 5.0; // Минимальный и максимальный коэффициенты зума. Камера не сможет отдалиться слишком далеко или приблизиться слишком близко. Значения подобраны эмпирически под размер стандартной карты.

    constructor(engine: RenderEngine2D) {
        this.engine = engine;
        const canvas = engine.getCanvas(); // Получает ссылку на HTML-элемент <canvas>, созданный движком. Именно на нём мы будем слушать события мыши.

        canvas.addEventListener('contextmenu', (e) => e.preventDefault()); // По правому клику мыши браузер обычно показывает контекстное меню («Копировать», «Сохранить картинку» и т.д.). Мы отключаем это поведение, чтобы правая кнопка могла быть использована в будущем (например, для тултипов) без помех.

        canvas.addEventListener('mousedown', (e: MouseEvent) => { // Когда пользователь нажимает левую кнопку мыши над canvas:
            if (e.button === 0) { // Проверяет, что нажата именно левая кнопка (0).
                this.isPanning = true; // Включает режим панорамирования.
                this.lastMouseX = e.clientX;
                this.lastMouseY = e.clientY; // Сохраняются текущие координаты курсора, чтобы от них считать смещение.
            }
        });

        window.addEventListener('mouseup', () => { // Завершение панорамирования (mouseup)
            this.isPanning = false; // // Когда пользователь отпускает кнопку мыши в любом месте окна (не обязательно над canvas), панорамирование выключается. Вешаем на window, чтобы избежать ситуации, когда курсор уходит за пределы canvas и mouseup не срабатывает.
        });

        canvas.addEventListener('mouseleave', () => { // Дополнительная страховка: если мышь покидает canvas (например, резко дёрнули), панорамирование тоже отключается. Без этого сцена могла бы «плыть» при возвращении курсора.
            this.isPanning = false;
        });

        canvas.addEventListener('mousemove', (e: MouseEvent) => { // Движение мыши с зажатой левой кнопкой (mousemove)
            if (!this.isPanning) return; // Если флаг isPanning не активен, просто выходим (ничего не делаем).
            const deltaX = e.clientX - this.lastMouseX;
            const deltaY = e.clientY - this.lastMouseY; // Вычисляем, на сколько пикселей сдвинулся курсор с прошлого вызова. e.clientX и e.clientY — координаты относительно всего окна браузера (а не только canvas), но для панорамирования важна именно разница, а не абсолютное положение.
            const camera = this.engine.getCamera(); // Сдвигаем камеру в сцене на ту же величину, но в противоположную сторону (знак минус для X, плюс для Y).
            camera.position.x -= deltaX;  // когда мы двигаем мышь вправо (deltaX > 0), мы хотим, чтобы сцена сдвинулась вправо относительно взгляда, а значит, камера должна уйти влево.
            camera.position.y += deltaY;  // Для Y логика инвертируется дважды: экранная ось Y направлена вниз, а сценная — вверх. Поэтому +deltaY (мышь вниз → камера вверх = сцена двигается вниз, что соответствует ожиданию пользователя).
            this.lastMouseX = e.clientX;
            this.lastMouseY = e.clientY;  // Запоминаем новые координаты для вычисления дельты в следующем кадре.
        });

        canvas.addEventListener('wheel', (e: WheelEvent) => { // Зум колёсиком (wheel)
            e.preventDefault(); // Срабатывает при прокрутке колёсика мыши. preventDefault() запрещает стандартное поведение (например, прокрутку страницы), чтобы зум работал корректно.
            const camera = this.engine.getCamera(); // Получаем камеру, чтобы менять её зум.
            if (e.deltaY > 0) {
                camera.zoom /= 1.1;
            } else {
                camera.zoom *= 1.1; // Если колесо прокрутили «вперёд» (deltaY > 0), уменьшаем зум (отдаляемся). Если «назад» — увеличиваем (приближаемся). Коэффициент 1.1 даёт плавное изменение без резких скачков.
            }
            camera.zoom = THREE.MathUtils.clamp(camera.zoom, this.minZoom, this.maxZoom); // Ограничиваем значение зума между 0.1 (очень далеко) и 5.0 (очень близко). THREE.MathUtils.clamp обрезает значение до указанного диапазона.
            camera.updateProjectionMatrix(); // После изменения camera.zoom обязательно нужно обновить матрицу проекции, иначе изменения не вступят в силу.
        });
    }
}